export interface SeasonInfo {
  id: 'spring' | 'summer' | 'autumn' | 'winter';
  name: string;
  emoji: string;
  months: string;
  palette: ThemePalette;
}

export function getCurrentSeason(): 'spring' | 'summer' | 'autumn' | 'winter' {
  const month = new Date().getMonth(); // 0-11
  if (month >= 2 && month <= 4) return 'spring'; // Mar, Apr, May
  if (month >= 5 && month <= 7) return 'summer'; // Jun, Jul, Aug
  if (month >= 8 && month <= 10) return 'autumn'; // Sep, Oct, Nov
  return 'winter'; // Dec, Jan, Feb
}

export function getSeasonInfo(season?: 'spring' | 'summer' | 'autumn' | 'winter'): SeasonInfo {
  const s = season || getCurrentSeason();
  const infoMap: Record<'spring' | 'summer' | 'autumn' | 'winter', { name: string; emoji: string; months: string }> = {
    spring: { name: 'Spring Blossom', emoji: '🌸', months: 'March – May' },
    summer: { name: 'Summer Sunshine', emoji: '☀️', months: 'June – August' },
    autumn: { name: 'Autumn Harvest', emoji: '🍂', months: 'September – November' },
    winter: { name: 'Winter Snow', emoji: '❄️', months: 'December – February' },
  };

  return {
    id: s,
    ...infoMap[s],
    palette: SEASONAL_PALETTES[s],
  };
}
